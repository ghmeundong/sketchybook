export function isKoreanLocale() {
  return isKorean;
}

export function translateText(value) {
  if (!isKorean || typeof value !== "string") return value;
  const normalized = value.trim().replace(/\s+/g, " ");
  if (koreanText[normalized]) return koreanText[normalized];
  for (const [pattern, replacement] of koreanPatterns) {
    if (pattern.test(normalized)) return normalized.replace(pattern, replacement);
  }
  return value;
}

function shouldSkipElement(element) {
  return Boolean(
    element?.closest(
      "script, style, textarea, [data-no-translate], .map-card-name, .my-map-card-title, .room-player-list li, .multiplayer-selection-players li, .auth-user-name"
    )
  );
}

function translateTextNode(node) {
  if (!node?.nodeValue?.trim() || shouldSkipElement(node.parentElement)) return;
  const currentValue = node.nodeValue;
  const previous = originalTextNodes.get(node);
  const original =
    previous && currentValue === previous.translated ? previous.original : currentValue;
  const leading = original.match(/^\s*/)?.[0] || "";
  const trailing = original.match(/\s*$/)?.[0] || "";
  const content = original.slice(leading.length, original.length - trailing.length || undefined);
  const translated = translateText(content);
  const nextValue = `${leading}${translated}${trailing}`;
  if (currentValue !== nextValue) node.nodeValue = nextValue;
  originalTextNodes.set(node, { original, translated: nextValue });
}

function translateElement(element) {
  if (!(element instanceof Element) || shouldSkipElement(element)) return;
  for (const attribute of translatedAttributes) {
    const currentValue = element.getAttribute(attribute);
    if (currentValue) {
      let savedAttributes = originalAttributes.get(element);
      if (!savedAttributes) {
        savedAttributes = new Map();
        originalAttributes.set(element, savedAttributes);
      }
      const previous = savedAttributes.get(attribute);
      const original =
        previous && currentValue === previous.translated ? previous.original : currentValue;
      const translated = translateText(original);
      if (translated !== currentValue) element.setAttribute(attribute, translated);
      savedAttributes.set(attribute, { original, translated });
    }
  }
  if (element instanceof HTMLInputElement && element.hasAttribute("value")) {
    let savedAttributes = originalAttributes.get(element);
    if (!savedAttributes) {
      savedAttributes = new Map();
      originalAttributes.set(element, savedAttributes);
    }
    const currentValue = element.getAttribute("value");
    const previous = savedAttributes.get("value");
    const original =
      previous && currentValue === previous.translated ? previous.original : currentValue;
    const translated = translateText(original);
    if (translated !== currentValue) element.setAttribute("value", translated);
    if (!element.matches(":focus") && element.value === currentValue) {
      element.value = translated;
    }
    savedAttributes.set("value", { original, translated });
  }
}

function translateTree(root) {
  if (root instanceof Element) translateElement(root);
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node = walker.nextNode();
  while (node) {
    translateTextNode(node);
    node = walker.nextNode();
  }
  if (root.querySelectorAll) root.querySelectorAll("*").forEach(translateElement);
}

export function setLanguage(language) {
  const normalizedLanguage = language === "ko" ? "ko" : "en";
  isKorean = normalizedLanguage === "ko";
  document.documentElement.lang = normalizedLanguage;
  setDisplayLanguage(isKorean);
  const pageDescription = document.querySelector('meta[name="description"]');
  if (pageDescription) pageDescription.content = pageDescriptions[normalizedLanguage];
  try {
    localStorage.setItem(languageStorageKey, normalizedLanguage);
  } catch {
    // Keep the current session language if browser storage is unavailable.
  }
  translateTree(document.body);
  const languageSelect = document.querySelector("[data-language-select]");
  if (languageSelect && languageSelect.value !== normalizedLanguage) {
    languageSelect.value = normalizedLanguage;
  }
  window.dispatchEvent(
    new CustomEvent("sketchybook:language-change", { detail: normalizedLanguage })
  );
}

export function initializeLocalization() {
  const language = navigator.languages?.[0] || navigator.language || "en";
  let savedLanguage = null;
  try {
    savedLanguage = localStorage.getItem(languageStorageKey);
  } catch {
    // Browser language remains the fallback when storage is unavailable.
  }
  const initialLanguage = savedLanguage || (language.toLowerCase().startsWith("ko") ? "ko" : "en");
  const languageSelect = document.querySelector("[data-language-select]");
  languageSelect?.addEventListener("change", () => setLanguage(languageSelect.value));
  setLanguage(initialLanguage);

  mutationObserver = new MutationObserver((mutations) => {
    for (const mutation of mutations) {
      if (mutation.type === "characterData") translateTextNode(mutation.target);
      if (mutation.type === "attributes") translateElement(mutation.target);
      mutation.addedNodes?.forEach((node) => {
        if (node.nodeType === Node.TEXT_NODE) translateTextNode(node);
        else if (node instanceof Element) translateTree(node);
      });
    }
  });
  mutationObserver.observe(document.body, {
    subtree: true,
    childList: true,
    characterData: true,
    attributes: true,
    attributeFilter: translatedAttributes,
  });
}
